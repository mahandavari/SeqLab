import {test,expect} from '@playwright/test'
import fs from 'node:fs/promises'
test('scientific workflow, persistence, exports and themes',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.getByText('Local server connected')).toBeVisible()
 await page.getByRole('button',{name:'New project',exact:true}).last().click()
 await page.getByLabel('Project title').fill('Browser validation '+Date.now())
 await page.getByRole('button',{name:'Create project',exact:true}).click()
 await page.getByRole('button',{name:'Import sequence',exact:true}).first().click()
 await page.getByLabel('Sequence or FASTA').fill('>reference\nATGAAATGA')
 await page.getByLabel('Molecule type').selectOption('DNA')
 await page.getByRole('button',{name:'Import sequences',exact:true}).click()
 await expect(page.getByRole('heading',{name:'reference',exact:true})).toBeVisible()
 await page.getByLabel('Window (nt)').fill('3')
 await page.getByLabel('Step (nt)').fill('3')
 await page.getByLabel('Minimum ORF length (nt)').fill('6')
 await page.getByRole('button',{name:'Run analysis',exact:true}).first().click()
 await expect(page.getByText('Analysis saved',{exact:true})).toBeVisible()
 await expect(page.locator('.metric').nth(1)).toContainText('22.22')
 await expect(page.locator('.metric').nth(2)).toContainText('1')
 await expect(page.locator('.js-plotly-plot')).toHaveCount(2)
 await expect(page.locator('.js-plotly-plot').first().locator('.main-svg').first()).toBeVisible()
 await page.screenshot({path:'../artifacts/seq-lab-light.png',fullPage:true})
 const csvDownload=page.waitForEvent('download')
 await page.getByRole('link',{name:'Download composition CSV'}).click()
 const csv=await csvDownload;await csv.saveAs('../artifacts/browser-composition.csv')
 expect(await fs.readFile('../artifacts/browser-composition.csv','utf8')).toContain('G,2')
 const pngDownload=page.waitForEvent('download')
 await page.locator('.js-plotly-plot').first().locator('a[data-title]').filter({has:page.locator('svg')}).all()
 await page.locator('.js-plotly-plot').first().locator('a[data-title]').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-title')))
 await page.locator('.js-plotly-plot').first().getByRole('button',{name:'Download plot as a PNG',exact:true}).click()
 const png=await pngDownload;await png.saveAs('../artifacts/composition.png')
 const svgDownload=page.waitForEvent('download')
 await page.locator('.js-plotly-plot').first().getByRole('button',{name:'Download SVG',exact:true}).click()
 const svg=await svgDownload;await svg.saveAs('../artifacts/composition.svg')
 expect((await fs.stat('../artifacts/composition.png')).size).toBeGreaterThan(1000)
 await page.getByRole('button',{name:'Translation',exact:true}).click()
 await expect(page.getByText('MK*',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'ORFs',exact:true}).click()
 await expect(page.getByRole('cell',{name:'1–9',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Dark appearance'}).click()
 await page.screenshot({path:'../artifacts/seq-lab-dark.png',fullPage:true})
 await page.getByLabel('Sequence operation').selectOption('reverse_complement')
 await expect(page.getByRole('heading',{name:/reference_reverse_complement/})).toBeVisible()
 await page.getByRole('button',{name:/Analysis History/}).click()
 await page.getByRole('button',{name:'Open',exact:true}).first().click()
 await expect(page.getByText('Analysis saved',{exact:true})).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:/Analysis History/}).click()
 await expect(page.getByText('completed',{exact:true})).toBeVisible()
 const reportDownload=page.waitForEvent('download')
 await page.getByRole('link',{name:'HTML report'}).click()
 const report=await reportDownload;await report.saveAs('../artifacts/browser-report.html')
 expect(await fs.readFile('../artifacts/browser-report.html','utf8')).toContain('Input SHA-256')
 await page.getByRole('button',{name:'Import sequence',exact:true}).first().click()
 await page.getByLabel('Sequence or FASTA').fill('>invalid\nATG?')
 await page.getByLabel('Molecule type').selectOption('DNA')
 await page.getByRole('button',{name:'Import sequences',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Invalid DNA symbols')
 await page.getByLabel('Sequence or FASTA').fill('>protein\nACDEFGHIKLMNPQRSTVWY')
 await page.getByLabel('Molecule type').selectOption('Protein')
 await page.getByRole('button',{name:'Import sequences',exact:true}).click()
 await page.getByRole('button',{name:'Run analysis',exact:true}).first().click()
 await expect(page.getByText('Analysis saved',{exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Theoretical protein properties'})).toBeVisible()
 await page.getByRole('button',{name:'Light appearance'}).click()
 await page.screenshot({path:'../artifacts/seq-lab-protein.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.locator('.js-plotly-plot').first().evaluate(el=>{const svg=el.querySelector('.main-svg');return !!svg&&Math.abs(svg.getBoundingClientRect().width-el.clientWidth)<2})).toBe(true)
 await page.screenshot({path:'../artifacts/seq-lab-mobile.png',fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 expect(errors).toEqual([])
})

test('file import, RNA transformation and parameter recomputation',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'New project',exact:true}).last().click()
 await page.getByLabel('Project title').fill('File workflow '+Date.now())
 await page.getByRole('button',{name:'Create project',exact:true}).click()
 await page.getByRole('button',{name:'Import sequence',exact:true}).first().click()
 await page.locator('input[type=file]').setInputFiles('../sample-data/intro-rna.fasta')
 await page.getByLabel('Molecule type').selectOption('RNA')
 await page.getByRole('button',{name:'Import sequences',exact:true}).click()
 await expect(page.getByRole('heading',{name:'reference_rna',exact:true})).toBeVisible()
 await page.getByLabel('Window (nt)').fill('3')
 await page.getByLabel('Step (nt)').fill('3')
 await page.getByRole('button',{name:'Run analysis',exact:true}).first().click()
 await expect(page.getByText('Analysis saved',{exact:true})).toBeVisible()
 await page.getByLabel('Window (nt)').fill('6')
 await expect(page.getByText(/Parameters changed/)).toBeVisible()
 await page.getByRole('button',{name:'Run analysis',exact:true}).first().click()
 await expect(page.getByText('Window 6 nt · step 3 nt · full windows only')).toBeVisible()
 await page.getByLabel('Region start').fill('2')
 await page.getByLabel('Region end').fill('4')
 await page.getByRole('button',{name:'Extract copy'}).click()
 await expect(page.getByRole('heading',{name:/reference_rna_subsequence/})).toBeVisible()
 await expect(page.locator('.sequence-lines')).toContainText('UGA')
 await page.getByLabel('Sequence operation').selectOption('back_transcribe')
 await expect(page.locator('.sequence-lines')).toContainText('TGA')
})
